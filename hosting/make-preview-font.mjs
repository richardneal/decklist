// Writes hosting/preview-font.mjs: Roboto rasterized, glyph by glyph, at the sizes the
// deck preview image draws (preview.mjs). The site Worker runs on the Workers Free plan,
// whose 10 ms of CPU a request can't fit a font rasterizer into, so the glyphs are drawn
// ahead of time and only copied into the image at run time.
//
// Uses the Playwright the browser tests install:
//   npm ci --prefix tests/browser
//   node hosting/make-preview-font.mjs
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';

const { chromium } = createRequire(new URL('../tests/browser/package.json', import.meta.url))('playwright');

// name: [CSS weight, size in px]
const FONTS = {
  brand: [700, 30],
  title: [700, 56],
  summary: [400, 28],
  leader: [700, 28],
  card: [400, 22],
  count: [700, 22],
  small: [400, 18],
  label: [700, 16]
};
// Printable ASCII, plus the separators the preview writes. preview.mjs folds other
// letters to these (Lim-Dûl to Lim-Dul).
const CHARS = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('') + '·…';

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<link href="https://fonts.googleapis.com/css2?family=Roboto:wght@400;700&display=block" rel="stylesheet">'
  + '<span style="font: 400 20px Roboto">a</span><span style="font: 700 20px Roboto">a</span>');
await page.evaluate(() => document.fonts.ready);

const fonts = await page.evaluate(({ FONTS, CHARS }) => {
  const out = {};
  for (const [name, [weight, size]] of Object.entries(FONTS)) {
    const font = `${weight} ${size}px Roboto`;
    if (!document.fonts.check(font)) throw new Error('Roboto did not load for ' + font);
    const canvas = document.createElement('canvas');
    canvas.width = canvas.height = size * 3;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    const baseline = size * 2;
    const glyphs = [];
    const nibbles = [];
    for (const ch of CHARS) {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      ctx.font = font;
      ctx.fillStyle = '#000';
      ctx.fillText(ch, size, baseline);
      const advance = ctx.measureText(ch).width;
      const { data } = ctx.getImageData(0, 0, canvas.width, canvas.height);
      let x0 = canvas.width, y0 = canvas.height, x1 = -1, y1 = -1;
      for (let y = 0; y < canvas.height; y++) {
        for (let x = 0; x < canvas.width; x++) {
          if (data[(y * canvas.width + x) * 4 + 3] >= 8) {
            x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
          }
        }
      }
      if (x1 < 0) { glyphs.push([Math.round(advance * 100), 0, 0, 0, 0]); continue; }
      for (let y = y0; y <= y1; y++) {
        for (let x = x0; x <= x1; x++) nibbles.push(Math.round(data[(y * canvas.width + x) * 4 + 3] / 17));
      }
      glyphs.push([Math.round(advance * 100), x0 - size, y0 - baseline, x1 - x0 + 1, y1 - y0 + 1]);
    }
    ctx.font = font;
    const metrics = ctx.measureText('Hg');
    out[name] = { size, ascent: Math.round(metrics.fontBoundingBoxAscent), glyphs, nibbles };
  }
  return out;
}, { FONTS, CHARS });

// The site's icon (images/favicon.svg) without its tile, as white coverage over the
// tile's blue, which the image's background shares
const ICON = 48;
const icon = await page.evaluate(async ({ svg, ICON }) => {
  const image = new Image();
  image.src = 'data:image/svg+xml;base64,' + btoa(svg);
  await image.decode();
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = ICON;
  const ctx = canvas.getContext('2d');
  ctx.drawImage(image, 0, 0, ICON, ICON);
  const { data } = ctx.getImageData(0, 0, ICON, ICON);
  const nibbles = [];
  for (let i = 0; i < ICON * ICON; i++) nibbles.push(Math.max(0, Math.min(15, Math.round((data[i * 4] - 0x1f) / (255 - 0x1f) * 15))));
  return nibbles;
}, { svg: await readFile(new URL('../images/favicon.svg', import.meta.url), 'utf8'), ICON });
await browser.close();

function pack(nibbles) {
  const bytes = Buffer.alloc(Math.ceil(nibbles.length / 2));
  nibbles.forEach((n, i) => { bytes[i >> 1] |= i & 1 ? n : n << 4; });
  return bytes.toString('base64');
}

let source = '// Generated by make-preview-font.mjs from Roboto (Apache License 2.0). Do not edit.\n'
  + '// Each font: its size, its ascent, and per character of CHARS [advance × 100, left and\n'
  + '// top of the bitmap from the pen position on the baseline, width, height]. data holds\n'
  + "// the bitmaps' coverage, 0–15, two pixels a byte, in base64.\n"
  + 'export const CHARS = ' + JSON.stringify(CHARS) + ';\n'
  + 'export const FONTS = {\n';
for (const [name, { size, ascent, glyphs, nibbles }] of Object.entries(fonts)) {
  source += `  ${name}: {\n    size: ${size}, ascent: ${ascent},\n    glyphs: ${JSON.stringify(glyphs)},\n`
    + `    data: '${pack(nibbles)}'\n  },\n`;
}
source += '};\n'
  + '// The site icon, ' + ICON + ' px square, in the same coverage form\n'
  + `export const ICON = { size: ${ICON}, data: '${pack(icon)}' };\n`;
await writeFile(new URL('./preview-font.mjs', import.meta.url), source);
console.log('Wrote hosting/preview-font.mjs, ' + Math.round(source.length / 1024) + ' KB');
